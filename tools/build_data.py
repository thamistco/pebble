import re, json, glob, os, sys
base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
acts = []; errs = []
def slug(s): return re.sub(r'[^a-z0-9]+','-',s.lower()).strip('-')
for f in sorted(glob.glob(base+'/content/a*.txt')):
    for blk in open(f).read().split('\n## ')[0:]:
        blk = blk.strip()
        if not blk: continue
        lines = blk.lstrip('# ').split('\n')
        title = lines[0].strip()
        meta = [x.strip() for x in lines[1].split('|')]
        if len(meta) < 6: errs.append((title,'meta')); continue
        a0,a1 = map(int, meta[0].split('-'))
        a = dict(id=slug(title), t=title, a=[a0,a1], m=int(meta[1]), e=meta[2], p=meta[3].split(','),
                 mat=meta[4], d=meta[5].split(','), tags=[x for x in (meta[6].split(',') if len(meta)>6 else []) if x], s=[])
        for l in lines[2:]:
            l=l.strip()
            if l.startswith('- '): a['s'].append(l[2:])
            elif ':' in l:
                k,v = l.split(':',1); k=k.strip(); v=v.strip()
                key = {'why':'w','easier':'ez','harder':'hd','safety':'sf','pl':'pl'}.get(k)
                if key: a[key]=v
                else: errs.append((title,'key '+k))
        for req in ['w','ez','hd']:
            if req not in a: errs.append((title,'missing '+req))
        if not (3<=len(a['s'])<=5): errs.append((title,'steps %d'%len(a['s'])))
        for p in a['p']:
            if p not in ['indoors','outdoors','bath','bedtime','kitchen','onthego']: errs.append((title,'place '+p))
        for d in a['d']:
            if d not in ['cl','pd','pse','lit','math','utw','ead']: errs.append((title,'area '+d))
        if a['e'] not in ['low','med','high']: errs.append((title,'energy'))
        if a['m'] not in [5,10,20,30]: errs.append((title,'min'))
        acts.append(a)
ids=[a['id'] for a in acts]
assert len(ids)==len(set(ids)), 'dup ids'
print(len(acts),'activities'); print('errors',errs)
json.dump(acts, open(base+'/content/activities.json','w'), ensure_ascii=False)
prompts = json.load(open(base+'/content/prompts.json'))
pl_rhymes = [
 {"t":"Jedzie pociąg z daleka","n":"Train song. Chug round the room holding hands."},
 {"t":"Kosi kosi łapci","n":"Clapping rhyme for little hands."},
 {"t":"Sroczka kaszkę warzyła","n":"Palm-circling finger rhyme, like Round and Round the Garden."},
 {"t":"Wlazł kotek na płotek","n":"Short, simple song, good for joining in."},
 {"t":"Aaa, kotki dwa","n":"Traditional lullaby."},
 {"t":"Panie Janie","n":"The Polish 'Frère Jacques'. Try it as a round."}
]
os.makedirs(base+'/js', exist_ok=True)
open(base+'/js/data.js','w').write('/* Generated by tools/build_data.py */\nwindow.PEBBLE_DATA=' + json.dumps({"activities":acts,"prompts":prompts,"plRhymes":pl_rhymes}, ensure_ascii=False) + ';\n')
print('prompts', len(prompts))
