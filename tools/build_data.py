import re, json, glob, os, sys, unicodedata
base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
acts = []; errs = []
def slug(s): return re.sub(r'[^a-z0-9]+','-',s.lower()).strip('-')
def slug_pl(s):
    s = s.lower().replace('ł','l')
    s = unicodedata.normalize('NFKD', s).encode('ascii','ignore').decode()
    return slug(s)
KEYS = {'why':'w','easier':'ez','harder':'hd','safety':'sf','pl':'pl','plp':'plp','words':'wd','en':'en','pn':'pn'}
ID_FIX = {'kosi-kosi-apci-clapping':'kosi-kosi-lapci-clapping'}   # slug lost its 'ł'; the app maps the old id on load
IMG_REV = {'pebble-sorting-on-the-beach':2, 'beach-pebble-tower':2}   # bump when a picture is redrawn, so cached copies refresh
imgs = {}
for line in open(base+'/content/images.tsv', encoding='utf-8'):
    p = line.rstrip('\n').split('\t')
    if len(p) == 3: imgs[p[0]] = (p[1], p[2])
for f in sorted(glob.glob(base+'/content/a*.txt')):
    legacy = not f.endswith('a5.txt')   # a1-a4 keep their original ids (saved favourites/moments use them)
    for blk in open(f, encoding='utf-8').read().split('\n## '):
        blk = blk.strip()
        if not blk: continue
        lines = blk.lstrip('# ').split('\n')
        title = lines[0].strip()
        meta = [x.strip() for x in lines[1].split('|')]
        if len(meta) < 6: errs.append((title,'meta')); continue
        a0,a1 = map(int, meta[0].split('-'))
        a = dict(id=ID_FIX.get(slug(title), slug(title)) if legacy else slug_pl(title), t=title, a=[a0,a1], m=int(meta[1]), e=meta[2], p=meta[3].split(','),
                 mat=meta[4], d=meta[5].split(','), tags=[x for x in (meta[6].split(',') if len(meta)>6 else []) if x], s=[])
        for l in lines[2:]:
            l=l.strip()
            if l.startswith('- '): a['s'].append(l[2:])
            elif ':' in l:
                k,v = l.split(':',1); k=k.strip(); v=v.strip()
                key = KEYS.get(k)
                if key: a[key]=v
                else: errs.append((title,'key '+k))
        for req in ['w','ez','hd']:
            if req not in a: errs.append((title,'missing '+req))
        if not (3<=len(a['s'])<=5): errs.append((title,'steps %d'%len(a['s'])))
        for p in a['p']:
            if p not in ['indoors','outdoors','bath','bedtime','kitchen','onthego']: errs.append((title,'place '+p))
        for d in a['d']:
            if d not in ['cl','pse','pd','lit','math','utw','ead']: errs.append((title,'area '+d))
        if a['e'] not in ['low','med','high']: errs.append((title,'energy'))
        if a['m'] not in [5,10,20,30]: errs.append((title,'min'))
        if a['id'] in imgs:
            alt, q = imgs[a['id']]
            if os.path.exists(base+'/img/'+a['id']+'.webp'): a['img'] = IMG_REV.get(a['id'], 1)
            a['alt'] = alt; a['yt'] = q
        else: errs.append((title,'no image row'))
        acts.append(a)
ids=[a['id'] for a in acts]
assert len(ids)==len(set(ids)), 'dup ids'
print(len(acts),'activities;', sum(1 for a in acts if a.get('img')),'with images;', sum(1 for a in acts if 'polish' in a['tags']),'in Polish collection;', sum(1 for a in acts if 'plp' in a),'with a Polish phrase')
print('errors',errs)
if errs: sys.exit(1)
json.dump(acts, open(base+'/content/activities.json','w'), ensure_ascii=False)
prompts = json.load(open(base+'/content/prompts.json'))
os.makedirs(base+'/js', exist_ok=True)
open(base+'/js/data.js','w').write('/* Generated by tools/build_data.py */\nwindow.PEBBLE_DATA=' + json.dumps({"activities":acts,"prompts":prompts}, ensure_ascii=False) + ';\n')
print('prompts', len(prompts))
